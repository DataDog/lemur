class TestDestinationPluginIntegration:

    def test_upload_without_binding(self, app):
        """
        Test DestinationPlugin.upload() with site_developer_name set to a
        value that won't find a Network record (expected warning, not error).
        Confirms deploy_signed_cert runs without raising.
        """
        from lemur.plugins.lemur_salesforce.plugin import SalesforceDestinationPlugin
        from lemur.plugins.base import plugins
        from unittest.mock import patch

        cert_name = _cert_name() + "_dest"

        # Get a real signed cert from DigiCert via IssuerPlugin
        from lemur.plugins.lemur_salesforce.sf_api import create_ca_signed_cert, get_csr
        create_ca_signed_cert(SF_ORG_URL, cert_name)
        sf_csr = get_csr(SF_ORG_URL, cert_name)

        digicert = plugins.get("digicert-issuer")
        body, chain, _ = digicert.create_certificate(sf_csr, {
            "common_name": "partners.datadoghq.com",
            "extensions": {"sub_alt_names": {"names": [
                {"name_type": "DNSName", "value": "partners.datadoghq.com"}
            ]}},
            "organization": {"name": "Datadog, Inc."},
            "validity_years": 1,
        })

        try:
            plugin = SalesforceDestinationPlugin()
            options = [
                {"name": "orgUrl", "value": SF_ORG_URL},
                {"name": "certDeveloperName", "value": cert_name},
                # Non-existent site — update_site_cert_binding will warn, not raise
                {"name": "siteDeveloperName", "value": "nonexistent_site_for_testing"},
                {"name": "domainName", "value": "partners.datadoghq.com"},
            ]
            # Should not raise — missing Network record logs a warning
            plugin.upload("integration-test", body, None, chain, options)
            print(f"\n✅ DestinationPlugin.upload() completed (binding skipped as expected)")
        finally:
            _cleanup_cert(cert_name)


# ---------------------------------------------------------------------------
# Cleanup helper
# ---------------------------------------------------------------------------

def _cleanup_cert(cert_name):
    """Delete a Certificate object from the dev org after a test.

    Best-effort — don't fail the test if cleanup fails.
    """
    try:
        from lemur.plugins.lemur_salesforce.sf_api import _session, _TOOLING
        session = _session(SF_ORG_URL)
        url = f"{_TOOLING.format(org_url=SF_ORG_URL)}/query"
        resp = session.get(url, params={
            "q": f"SELECT Id FROM Certificate WHERE DeveloperName = '{cert_name}'"
        }, timeout=15)
        records = resp.json().get("records", [])
        for r in records:
            session.delete(
                f"{_TOOLING.format(org_url=SF_ORG_URL)}/sobjects/Certificate/{r['Id']}",
                timeout=15,
            )
    except Exception as e:
        print(f"  [cleanup warning] Could not delete '{cert_name}': {e}")
