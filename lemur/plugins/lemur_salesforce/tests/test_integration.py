# sf_api layer tests
# ---------------------------------------------------------------------------

class TestSfApiIntegration:
    """Test sf_api.py functions against a live Salesforce Developer Edition org."""

    def test_get_access_token(self, app):
        """JWT Bearer auth should return a non-empty access token."""
        from lemur.plugins.lemur_salesforce.sf_api import _get_access_token
        token = _get_access_token(SF_ORG_URL, SF_CONSUMER_KEY, SF_PRIVATE_KEY)
        assert token, "Expected a non-empty access token"
        assert len(token) > 20

    def test_list_certificates_returns_list(self, app):
        """list_certificates should return a list (may be empty on fresh org)."""
        from lemur.plugins.lemur_salesforce.sf_api import list_certificates
        certs = list_certificates(SF_ORG_URL)
        assert isinstance(certs, list)
        # Each entry must have the shape Lemur's SourcePlugin expects
        for c in certs:
            assert "body" in c
            assert "chain" in c
            assert "name" in c
            assert "BEGIN CERTIFICATE" in c["body"]

    def test_create_cert_and_get_csr(self, app):
        """create_ca_signed_cert should trigger Salesforce key gen; get_csr returns PEM CSR."""
        from lemur.plugins.lemur_salesforce.sf_api import create_ca_signed_cert, get_csr

        cert_name = _cert_name()
        try:
            create_ca_signed_cert(SF_ORG_URL, cert_name)
            csr = get_csr(SF_ORG_URL, cert_name)

            assert "BEGIN CERTIFICATE REQUEST" in csr, (
                f"Expected PEM CSR, got: {csr[:200]}"
            )
            print(f"\n✅ CSR generated by Salesforce for '{cert_name}':")
            print(csr[:120], "...")
        finally:
            # Best-effort cleanup — delete the cert object from the dev org
            _cleanup_cert(cert_name)

    def test_full_sf_api_flow(self, app):
        """create cert → get CSR → verify CSR is well-formed."""
        from lemur.plugins.lemur_salesforce.sf_api import create_ca_signed_cert, get_csr
        import base64, re

        cert_name = _cert_name() + "_flow"
        try:
            create_ca_signed_cert(SF_ORG_URL, cert_name)
            csr_pem = get_csr(SF_ORG_URL, cert_name)

            # Basic PEM structure check
            assert csr_pem.strip().startswith("-----BEGIN CERTIFICATE REQUEST-----")
            assert "-----END CERTIFICATE REQUEST-----" in csr_pem

            # Base64 body should be valid
            body = re.sub(r"-----.*?-----", "", csr_pem).replace("\n", "").strip()
            decoded = base64.b64decode(body)
            assert len(decoded) > 100, "CSR DER content too short"
        finally:
            _cleanup_cert(cert_name)


