class TestEndToEndRotation:
    """
    Full rotation flow using a real Salesforce Developer Edition org and
    Datadog's DigiCert account.

    DigiCert prerequisite: DCV must be current for partners.datadoghq.com
    in the DigiCert org (DIGICERT_ORG_ID). Issuance uses a test CN with
    partners.datadoghq.com as the SAN — DigiCert accepts the Salesforce-
    generated CSR and attaches our SANs independently.
    """

    def test_create_sign_upload(self, app):
        """
        Full flow:
          1. Create cert in Salesforce (generates key + CSR)
          2. Submit CSR to DigiCert → signed cert
          3. Upload signed cert back to Salesforce
          4. Confirm cert appears in list_certificates()
        """
        from lemur.plugins.lemur_salesforce.sf_api import (
            create_ca_signed_cert,
            get_csr,
            deploy_signed_cert,
            list_certificates,
        )
        from lemur.plugins.base import plugins

        cert_name = _cert_name() + "_e2e"
        try:
            # 1. Salesforce generates key pair + CSR
            print(f"\n[1/4] Creating Salesforce cert object '{cert_name}'...")
            create_ca_signed_cert(SF_ORG_URL, cert_name)

            print(f"[2/4] Retrieving CSR from Salesforce...")
            sf_csr = get_csr(SF_ORG_URL, cert_name)
            assert "BEGIN CERTIFICATE REQUEST" in sf_csr

            # 2. Sign via DigiCert — uses existing DCV for datadoghq.com
            print(f"[3/4] Submitting CSR to DigiCert...")
            digicert = plugins.get("digicert-issuer")
            issuer_options = {
                # DigiCert uses dns_names from the order, not from the CSR subject
                "common_name": "partners.datadoghq.com",
                "extensions": {
                    "sub_alt_names": {
                        "names": [
                            {"name_type": "DNSName", "value": "partners.datadoghq.com"}
                        ]
                    }
                },
                "organization": {"name": "Datadog, Inc."},
                "validity_years": 1,
            }
            body, chain, external_id = digicert.create_certificate(sf_csr, issuer_options)
            assert body and "BEGIN CERTIFICATE" in body, "DigiCert did not return a cert body"
            assert external_id, "DigiCert did not return an external_id"
            print(f"    ✅ DigiCert issued cert (external_id={external_id})")

            # 3. Upload signed cert back to Salesforce
            print(f"[4/4] Deploying signed cert back to Salesforce...")
            pem_bundle = body.rstrip() + "\n" + chain.strip() if chain else body
            deploy_id = deploy_signed_cert(SF_ORG_URL, cert_name, pem_bundle)
            assert deploy_id, "No deploy ID returned"
            print(f"    ✅ Deploy started (deploy_id={deploy_id}), cert active in 4–8h")

            # 4. Confirm cert now appears in inventory (poll briefly — deploy is async)
            print(f"    Waiting 10s for Salesforce to process deploy...")
            time.sleep(10)
            certs = list_certificates(SF_ORG_URL)
            names = [c["name"] for c in certs]
            # Note: cert may still be deploying; list_certificates shows cert objects
            # that exist in the org regardless of deploy state
            print(f"    Certs in org: {names}")

        finally:
            _cleanup_cert(cert_name)

    def test_salesforce_issuer_plugin_e2e(self, app):
        """
        Full SalesforceIssuerPlugin.create_certificate() end-to-end.
        Verifies the plugin correctly discards Lemur's CSR, substitutes
        Salesforce's, delegates to DigiCert, and returns the right tuple shape.
        """
        from lemur.plugins.lemur_salesforce.plugin import SalesforceIssuerPlugin

        cert_name = _cert_name() + "_plugin"
        plugin = SalesforceIssuerPlugin()
        issuer_options = {
            "orgUrl": SF_ORG_URL,
            "certDeveloperName": cert_name,
            "common_name": "partners.datadoghq.com",
            "extensions": {
                "sub_alt_names": {
                    "names": [
                        {"name_type": "DNSName", "value": "partners.datadoghq.com"}
                    ]
                }
            },
            "organization": {"name": "Datadog, Inc."},
            "validity_years": 1,
        }

        try:
            body, chain, external_id = plugin.create_certificate(
                "LEMUR_GENERATED_CSR_SHOULD_BE_IGNORED", issuer_options
            )
            assert "BEGIN CERTIFICATE" in body
            assert external_id
            print(f"\n✅ SalesforceIssuerPlugin end-to-end: external_id={external_id}")
        finally:
            _cleanup_cert(cert_name)


